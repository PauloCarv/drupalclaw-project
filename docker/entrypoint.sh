#!/bin/bash
# entrypoint.sh — Runs before PiClaw starts.
# Syncs baked-in Drupal skills/templates/config to the mounted workspace.

set -e

WORKSPACE="/workspace"
# Sources baked into the image under /opt/drupalclaw (not hidden by the /config bind mount).
# Falls back to /home/agent/.pi for images built before this layout.
BAKED="/opt/drupalclaw"
SKILLS_SRC="$BAKED/skills"
TEMPLATES_SRC="$BAKED/templates"
AGENT_CONFIG="$BAKED/agent"
ICON_PATH="$BAKED/assets/drupal_claw_icon.png"
[[ -d "$SKILLS_SRC" ]] || SKILLS_SRC="/home/agent/.pi/skills"
[[ -d "$TEMPLATES_SRC" ]] || TEMPLATES_SRC="/home/agent/.pi/templates"
[[ -d "$AGENT_CONFIG" ]] || AGENT_CONFIG="/home/agent/.pi/agent"
[[ -f "$ICON_PATH" ]] || ICON_PATH="/home/agent/.pi/assets/drupal_claw_icon.png"

# -- Initialize PiClaw agent config on the native Docker volume --
AGENT_DIR="/config/.pi/agent"
LEGACY_AGENT_DIR="/legacy-agent"
MIGRATION_MARKER="$AGENT_DIR/.drupalclaw-migrated"

mkdir -p "$AGENT_DIR"
echo "[drupalclaw] ensured agent directory: $AGENT_DIR"

if [[ ! -e "$MIGRATION_MARKER" ]]; then
  if [[ -d "$LEGACY_AGENT_DIR" ]]; then
    for runtime_file in \
      auth.json \
      models-store.json \
      mcp-cache.json \
      messages.db \
      messages.db-wal \
      messages.db-shm; do
      if [[ -f "$LEGACY_AGENT_DIR/$runtime_file" && ! -e "$AGENT_DIR/$runtime_file" ]]; then
        cp -p "$LEGACY_AGENT_DIR/$runtime_file" "$AGENT_DIR/$runtime_file"
        echo "[drupalclaw] migrated agent file: $runtime_file"
      fi
    done

    for runtime_dir in sessions prompts themes extensions; do
      if [[ -d "$LEGACY_AGENT_DIR/$runtime_dir" ]]; then
        mkdir -p "$AGENT_DIR/$runtime_dir"
        cp -a -n "$LEGACY_AGENT_DIR/$runtime_dir/." "$AGENT_DIR/$runtime_dir/"
        echo "[drupalclaw] migrated missing agent directory contents: $runtime_dir"
      fi
    done
    touch "$MIGRATION_MARKER"
    echo "[drupalclaw] marked legacy agent migration complete"
  else
    echo "[drupalclaw] legacy agent directory not found; migration deferred"
  fi
fi

for managed_file in AGENTS.md dev-panel.json; do
  if [[ -f "$AGENT_CONFIG/$managed_file" ]]; then
    cp "$AGENT_CONFIG/$managed_file" "$AGENT_DIR/$managed_file"
    echo "[drupalclaw] refreshed managed agent file: $managed_file"
  fi
done

if [[ ! -e "$AGENT_DIR/settings.json" && -f "$AGENT_CONFIG/settings.json" ]]; then
  cp "$AGENT_CONFIG/settings.json" "$AGENT_DIR/settings.json"
  echo "[drupalclaw] seeded agent settings.json"
fi

if [[ -d "$AGENT_CONFIG/skills" ]]; then
  mkdir -p "$AGENT_DIR/skills"
  for skill_group in "$AGENT_CONFIG/skills"/*/; do
    [[ -d "$skill_group" ]] || continue
    skill_group_name=$(basename "$skill_group")
    mkdir -p "$AGENT_DIR/skills/$skill_group_name"

    for skill_dir in "$skill_group"*/; do
      [[ -d "$skill_dir" ]] || continue
      skill_name=$(basename "$skill_dir")
      if [[ ! -e "$AGENT_DIR/skills/$skill_group_name/$skill_name" ]]; then
        cp -a "$skill_dir" "$AGENT_DIR/skills/$skill_group_name/"
        echo "[drupalclaw] seeded agent skill: $skill_group_name/$skill_name"
      fi
    done
  done
fi

chown -R agent:agent "$AGENT_DIR"
echo "[drupalclaw] set agent directory ownership to agent:agent"

# -- Sync Drupal skills to workspace (copy only if missing — never overwrite user changes) --
if [[ -d "$SKILLS_SRC" ]]; then
  mkdir -p "$WORKSPACE/.pi/skills"
  for skill_dir in "$SKILLS_SRC"/*/; do
    if [[ -d "$skill_dir" ]]; then
      skill_name=$(basename "$skill_dir")
      if [[ ! -f "$WORKSPACE/.pi/skills/$skill_name/SKILL.md" ]]; then
        cp -r "$skill_dir" "$WORKSPACE/.pi/skills/"
      fi
    fi
  done
fi

# -- Sync templates --
if [[ -d "$TEMPLATES_SRC" ]]; then
  mkdir -p "$WORKSPACE/.piclaw/stack"
  for tpl in "$TEMPLATES_SRC"/*; do
    tpl_name=$(basename "$tpl")
    if [[ ! -f "$WORKSPACE/.piclaw/stack/$tpl_name" ]] || \
       [[ "$tpl" -nt "$WORKSPACE/.piclaw/stack/$tpl_name" ]]; then
      cp "$tpl" "$WORKSPACE/.piclaw/stack/"
    fi
  done
fi

# -- Sync config (always overwrite — ensures DrupalClaw config is applied) --
mkdir -p "$WORKSPACE/.piclaw"
cp "$AGENT_CONFIG/AGENTS.md" "$WORKSPACE/AGENTS.md" 2>/dev/null || true
cp "$AGENT_CONFIG/dev-panel.json" "$WORKSPACE/.piclaw/dev-panel.json" 2>/dev/null || true

# -- Generate .env.sh with branding (only if missing) --
if [[ ! -f "$WORKSPACE/.env.sh" ]]; then
  AVATAR_DATA=""
  if [[ -f "$ICON_PATH" ]]; then
    AVATAR_B64=$(base64 "$ICON_PATH" | tr -d '\n')
    AVATAR_DATA="data:image/png;base64,${AVATAR_B64}"
  fi

  cat > "$WORKSPACE/.env.sh" << EOF
# DrupalClaw environment — auto-generated by entrypoint.sh
export PICLAW_ASSISTANT_NAME="DrupalClaw"
EOF
  if [[ -n "$AVATAR_DATA" ]]; then
    echo "export PICLAW_ASSISTANT_AVATAR=\"${AVATAR_DATA}\"" >> "$WORKSPACE/.env.sh"
  fi
fi

# -- Seed user-prefs.json if missing (required for frontend PUT to work) --
if [[ ! -f "$WORKSPACE/.piclaw/user-prefs.json" ]]; then
  echo '{"interaction_mode":"learning"}' > "$WORKSPACE/.piclaw/user-prefs.json"
fi

# -- Seed plans directory --
mkdir -p "$WORKSPACE/.piclaw/plans/runs"

# -- Heal stack state: ensure state.json and workspace-id match running containers --
STATE_FILE="$WORKSPACE/.piclaw/stack/state.json"
WORKSPACE_ID_FILE="$WORKSPACE/.piclaw/workspace-id"
if [[ -f "$STATE_FILE" ]]; then
  PROJECT_NAME=$(grep -o '"project_name":"[^"]*"' "$STATE_FILE" 2>/dev/null | cut -d'"' -f4)
  if [[ -n "$PROJECT_NAME" ]]; then
    RUNNING=$(docker ps -a --filter "label=com.docker.compose.project=${PROJECT_NAME}" --format '{{.Names}}' 2>/dev/null | head -1)
    if [[ -z "$RUNNING" ]]; then
      # State is stale — try to find actual running Drupal project
      ACTUAL_PROJECT=$(docker ps --format '{{.Label "com.docker.compose.project"}}' 2>/dev/null | grep '^drupal-' | head -1)
      if [[ -n "$ACTUAL_PROJECT" ]]; then
        ACTUAL_ID="${ACTUAL_PROJECT#drupal-}"
        python3 -c "
import json, sys
with open('$STATE_FILE') as f: s = json.load(f)
s['project_name'] = '$ACTUAL_PROJECT'
s['workspace_id'] = '$ACTUAL_ID'
with open('$STATE_FILE', 'w') as f: json.dump(s, f, indent=2)
" 2>/dev/null || true
        echo "$ACTUAL_ID" > "$WORKSPACE_ID_FILE"
      else
        rm -f "$STATE_FILE"
      fi
    fi
  fi
fi
# Ensure workspace-id is consistent with valid state.json
if [[ -f "$STATE_FILE" && ! -f "$WORKSPACE_ID_FILE" ]]; then
  PROJECT_NAME=$(grep -o '"project_name":"[^"]*"' "$STATE_FILE" 2>/dev/null | cut -d'"' -f4)
  WS_ID="${PROJECT_NAME#drupal-}"
  [[ -n "$WS_ID" ]] && echo "$WS_ID" > "$WORKSPACE_ID_FILE"
fi

# -- Fix Docker socket permissions (lost on Docker Desktop restart) --
chmod 666 /var/run/docker.sock 2>/dev/null || true

# -- Ensure DrupalClaw redirect is in place --
# PiClaw routes GET / to static/classic/index.html (dispatch-shell.ts), never to static/index.html
PICLAW_STATIC=$(find /usr/local/lib/bun -path "*/piclaw/runtime/web/static" -type d 2>/dev/null | head -1)
if [[ -n "$PICLAW_STATIC" ]]; then
  echo '<!DOCTYPE html><html><head><script>window.location.replace("/static/drupalclaw/index.html")</script></head><body></body></html>' \
    > "$PICLAW_STATIC/classic/index.html"
fi

# -- Hand off to original PiClaw entrypoint --
exec /entrypoint-piclaw.sh "$@"
